"""Відбиток (хеш) секретних токенів для зберігання.

Чому SHA-256, а не Argon2, як для паролів? Пароль придумує людина, і
його можна підібрати перебором словника, тож потрібна *повільна*
функція. Токен — це 256 біт криптографічної випадковості: перебір
неможливий за будь-якої швидкості хешування. Тому досить швидкої
функції, а детермінований результат дозволяє шукати сесію в БД за
індексом ``token_hash``.
"""

from __future__ import annotations

import hashlib


def hash_token(token: str) -> str:
    """Повертає шістнадцятковий SHA-256 відбиток токена.

    Args:
        token: Токен у тому вигляді, в якому його отримав клієнт.

    Returns:
        Рядок із 64 шістнадцяткових символів.
    """
    return hashlib.sha256(token.encode("utf-8")).hexdigest()


